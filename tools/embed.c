/* embed.c — packs text assets (*.spr) into a C file as byte arrays (portable: no limits on the
 * length of string literals).
 * Usage: embed OUT.c file1.spr file2.spr ...
 * Files whose name starts with "palette" go first (the others refer to them). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *base(const char *p)
{
    const char *s = strrchr(p, '/');
    return s ? s + 1 : p;
}

static void emit(FILE *out, const char *path, int idx)
{
    FILE *in = fopen(path, "rb");
    if (!in) { perror(path); exit(1); }
    fprintf(out, "static const char asset_%d[] = {", idx);
    int c, col = 0;
    while ((c = fgetc(in)) != EOF) {
        if (c == '\r') continue;
        if (col++ % 24 == 0) fputs("\n   ", out);
        /* bytes >= 128 (UTF-8) via a cast: works whether char is signed or not */
        if (c < 128) fprintf(out, " %d,", c);
        else fprintf(out, " (char)%d,", c);
    }
    fputs("\n    0\n};\n\n", out);
    fclose(in);
}

int main(int argc, char **argv)
{
    if (argc < 2) { fprintf(stderr, "usage: embed OUT.c files...\n"); return 1; }
    FILE *out = fopen(argv[1], "w");
    if (!out) { perror(argv[1]); return 1; }
    int n = argc - 2;
    const char **order = malloc(sizeof *order * (size_t)(n + 1));
    int k = 0;
    for (int pass = 0; pass < 2; pass++)
        for (int i = 0; i < n; i++) {
            int pal = strncmp(base(argv[i + 2]), "palette", 7) == 0;
            if ((pass == 0) == pal) order[k++] = argv[i + 2];
        }
    fputs("/* generated by tools/embed — do not edit */\n\n", out);
    for (int i = 0; i < n; i++) emit(out, order[i], i);
    fputs("const char *const nf_embedded_names[] = {\n", out);
    for (int i = 0; i < n; i++) fprintf(out, "    \"%s\",\n", base(order[i]));
    fputs("    0\n};\n\nconst char *const nf_embedded_assets[] = {\n", out);
    for (int i = 0; i < n; i++) fprintf(out, "    asset_%d,\n", i);
    fputs("    0\n};\n", out);
    fclose(out);
    free(order);
    return 0;
}
